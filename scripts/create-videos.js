const fs = require('fs');
const path = require('path');

const videosDir = path.join(__dirname, '..', 'public', 'videos');
if (!fs.existsSync(videosDir)) fs.mkdirSync(videosDir, { recursive: true });

// Minimal valid MP4 container buffer (H.264 / AAC compliant dummy container)
function createMinimalMp4() {
  const ftyp = Buffer.from([
    0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, // size 24, 'ftyp'
    0x6d, 0x70, 0x34, 0x32, 0x00, 0x00, 0x00, 0x00, // 'mp42', minor 0
    0x6d, 0x70, 0x34, 0x32, 0x69, 0x73, 0x6f, 0x6d  // compatible brands
  ]);

  const moov = Buffer.from([
    0x00, 0x00, 0x00, 0x6c, 0x6d, 0x6f, 0x6f, 0x76, // 'moov'
    0x00, 0x00, 0x00, 0x64, 0x6d, 0x76, 0x68, 0x64, // 'mvhd'
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0xe8, // timescale 1000
    0x00, 0x00, 0x03, 0xe8, 0x00, 0x01, 0x00, 0x00, // duration 1000
    0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x02
  ]);

  const mdat = Buffer.from([
    0x00, 0x00, 0x00, 0x08, 0x6d, 0x64, 0x61, 0x74 // 'mdat'
  ]);

  return Buffer.concat([ftyp, moov, mdat]);
}

const sampleMp4 = createMinimalMp4();

const videoFiles = [
  'intro.mp4',
  'transformation-1.mp4',
  'transformation-2.mp4',
  'transformation-3.mp4',
  'transformation-4.mp4',
  'transformation-5.mp4',
  'transformation-6.mp4'
];

videoFiles.forEach(name => {
  fs.writeFileSync(path.join(videosDir, name), sampleMp4);
});

console.log('Sample video files created in public/videos/');
